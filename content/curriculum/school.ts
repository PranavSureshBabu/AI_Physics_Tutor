import type { Chapter, SketchName, Topic, WorkedInput } from "../types";

type QuizSeed = { q: string; choices: string[]; answer: number; why: string };

type Seed = {
  id: string;
  title: string;
  aliases: string[];
  idea: string;
  younger: string;
  senior?: string;
  example: string;
  formulaIds?: string[];
  sketch: SketchName;
  sketchCaption: string;
  mistake: [string, string];
  check: [string, string];
  keyPoints: string[];
  practice: [string, string, string];
  quiz: QuizSeed[];
  worked?: WorkedInput & { prompt: string; after?: string };
};

function topic(seed: Seed): Topic {
  return {
    id: seed.id,
    title: seed.title,
    aliases: seed.aliases,
    idea: seed.idea,
    younger: seed.younger,
    senior: seed.senior,
    example: seed.example,
    formulaIds: seed.formulaIds ?? [],
    sketch: seed.sketch,
    sketchCaption: seed.sketchCaption,
    mistake: { wrong: seed.mistake[0], right: seed.mistake[1] },
    check: { question: seed.check[0], answer: seed.check[1] },
    keyPoints: seed.keyPoints,
    practice: [
      {
        id: `${seed.id}-p1`,
        question: seed.practice[0],
        hint: seed.practice[1],
        answer: seed.practice[2],
      },
    ],
    quiz: seed.quiz.map((item, index) => ({
      id: `${seed.id}-q${index + 1}`,
      question: item.q,
      choices: item.choices,
      answerIndex: item.answer,
      explanation: item.why,
    })),
    worked: seed.worked,
  };
}

function chapter(
  id: string,
  grade: number,
  title: string,
  promise: string,
  scopeNote: string,
  topics: Topic[],
): Chapter {
  return { id, grade, title, promise, scopeNote, topics };
}

